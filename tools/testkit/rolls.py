"""The DK roll numbers per paper for the test kit: writes tools/testkit/rolls.tsv (make-testkit.ps1 runs it).

Kept out of driver/gen: the driver's version hash covers driver/gen (driver/gen/version.py), and these numbers
never reach the driver or the programs (as Brother's driver shows none). The papers come from driver/gen/media.py.

Run:  python -I tools/testkit/rolls.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "driver", "gen"))
import media  # noqa: E402

# The DK roll for each paper (by PTD paper name), European and US number, for the docs and the test kit.
# Checked against supplies lists 2026-11-03; US "" = no US number found. Third value True: more rolls share the
# size (film, removable, colours), the number is an example. No entry: no DK roll known for the paper.
DK_ROLLS = {
    "17mm x 54mm": ("DK-11204", "DK-1204", False), "17mm x 87mm": ("DK-11203", "DK-1203", False),
    "23mm x 23mm": ("DK-11221", "DK-1221", False), "29mm x 42mm": ("DK-11215", "", False),
    "29mm x 90mm": ("DK-11201", "DK-1201", False), "38mm x 90mm": ("DK-11208", "DK-1208", False),
    "39mm x 48mm": ("DK-11220", "DK-1220", False), "52mm x 29mm": ("DK-11226", "", False),
    "60mm x 86mm": ("DK-11234", "DK-1234", False), "62mm x 29mm": ("DK-11209", "DK-1209", False),
    "62mm x 100mm": ("DK-11202", "DK-1202", False),
    "12mm Dia": ("DK-11219", "DK-1219", False), "24mm Dia": ("DK-11218", "DK-1218", False),
    "58mm Dia": ("DK-11207", "DK-1207", False),
    "102mm x 51mm": ("DK-11240", "DK-1240", False), "102mm x 152mm": ("DK-11241", "DK-1241", False),
    "103mm x 164mm": ("DK-11247", "DK-1247", False),
    "12mm": ("DK-22214", "DK-2214", False), "29mm": ("DK-22210", "DK-2210", True), "38mm": ("DK-22225", "DK-2225", False),
    "50mm": ("DK-22223", "DK-2223", False), "54mm": ("DK-N55224", "", False), "62mm": ("DK-22205", "DK-2205", True),
    "102mm": ("DK-22243", "DK-2243", False), "103mm": ("DK-22246", "DK-2246", False),
}
TWO_COLOR_ROLL = ("DK-22251", "DK-2251")   # 62 mm black/red
ROLLS_TSV = os.path.join(HERE, "rolls.tsv")


def rolls_tsv(papers):
    """rolls.tsv: the DK roll per paper id (European and US number)."""
    rows = ["# Generated by tools/testkit/rolls.py (DK_ROLLS) - do not edit.",
            "# paper id, paper name, DK roll (Europe), DK roll (US, empty: none known), 1: more rolls of this size (e.g.)"]
    seen = set()
    for m in papers:
        if m["ptd_id"] not in seen and m["name"] in DK_ROLLS:
            seen.add(m["ptd_id"])
            eu, us, several = DK_ROLLS[m["name"]]
            rows.append("\t".join((str(m["ptd_id"]), m["name"], eu, us, str(int(several)))))
    rows.append("\t".join(("two-color", "62mm black/red") + TWO_COLOR_ROLL + ("0",)))
    return "\n".join(rows) + "\n"


def main():
    papers = media.single(media.all_media())
    unknown = set(DK_ROLLS) - {m["name"] for m in papers}
    if unknown:
        raise SystemExit(f"DK_ROLLS: no such paper: {', '.join(sorted(unknown))}")
    with open(ROLLS_TSV, "w", encoding="ascii", newline="\r\n") as f:
        f.write(rolls_tsv(papers))
    print(f"rolls.tsv: {len(DK_ROLLS)} papers with DK rolls")


if __name__ == "__main__":
    main()
